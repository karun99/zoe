#!/usr/bin/env bash
# Project Zoe - Termux (Android) installer.
#
#   bash scripts/termux-install.sh                    # Ollama + qwen2.5:0.5b
#   bash scripts/termux-install.sh --model llama3.2:1b
#   bash scripts/termux-install.sh --backend llama-cli --model-file ~/models/tiny.gguf
#   bash scripts/termux-install.sh --no-ollama        # keep the mock engine only
#   bash scripts/termux-install.sh --dry-run          # show what would be written
#
# Everything is idempotent: re-running upgrades the venv and re-checks the
# environment. Nothing is installed outside $HOME except Termux packages.
set -euo pipefail

BACKEND="ollama"
BACKEND_SET=0
MODEL="${ZOE_OLLAMA_MODEL:-qwen2.5:0.5b}"
MODEL_FILE="${ZOE_GGUF_PATH:-}"
WANT_OLLAMA=1
PULL_MODEL=1
USE_VENV=1
ASSUME_YES=0
DRY_RUN=0

ZOE_HOME="${ZOE_HOME:-$HOME/.zoe}"
VENV="$ZOE_HOME/venv"
ENV_FILE="$ZOE_HOME/env"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

say()  { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[!]\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31m[x]\033[0m %s\n' "$*" >&2; exit 1; }

usage() {
  sed -n '2,11p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
  exit 0
}

while [ $# -gt 0 ]; do
  case "$1" in
    --backend)      BACKEND="${2:?}"; BACKEND_SET=1; shift 2 ;;
    --model)        MODEL="${2:?}"; shift 2 ;;
    --model-file)   MODEL_FILE="${2:?}"; shift 2 ;;
    --no-ollama)    WANT_OLLAMA=0; PULL_MODEL=0; shift ;;
    --no-pull)      PULL_MODEL=0; shift ;;
    --no-venv)      USE_VENV=0; shift ;;
    --dry-run)      DRY_RUN=1; shift ;;
    --yes|-y)       ASSUME_YES=1; shift ;;
    -h|--help)      usage ;;
    *) die "unknown option: $1 (try --help)" ;;
  esac
done

# --no-ollama means "mock only" unless the user explicitly chose a backend.
if [ "$WANT_OLLAMA" -eq 0 ] && [ "$BACKEND_SET" -eq 0 ]; then
  BACKEND="mock"
fi

is_termux() {
  [ -n "${TERMUX_VERSION:-}" ] && return 0
  case "${PREFIX:-}" in *com.termux*) return 0 ;; esac
  [ -d /data/data/com.termux/files/usr ]
}

if ! is_termux; then
  warn "This script targets Termux on Android; ${PREFIX:-this system} does not look like it."
  warn "On desktop Linux/macOS use: pip install -e '.[llm]' and ZOE_LLM_BACKEND=ollama"
  [ "$ASSUME_YES" -eq 1 ] || die "refusing to run without --yes"
fi

write_env() {
  cat <<EOF
# Project Zoe environment - generated by scripts/termux-install.sh
export ZOE_LLM_BACKEND="$BACKEND"
export ZOE_OLLAMA_MODEL="$MODEL"
EOF
  if [ -n "$MODEL_FILE" ]; then
    printf 'export ZOE_GGUF_PATH="%s"\n' "$MODEL_FILE"
  fi
  printf 'export ZOE_LEDGER_PATH="%s/ledger.jsonl"\n' "$ZOE_HOME"
  if [ "$USE_VENV" -eq 1 ]; then
    # shellcheck disable=SC2016  # $PATH must stay literal in the env file
    printf 'export PATH="%s/bin:$PATH"\n' "$VENV"
  fi
}

if [ "$DRY_RUN" -eq 1 ]; then
  say "dry run - nothing will be installed"
  say "repo: $REPO_ROOT"
  say "backend: $BACKEND"
  say "model: $MODEL"
  if [ -n "$MODEL_FILE" ]; then say "gguf: $MODEL_FILE"; fi
  say "env file: $ENV_FILE"
  printf '\n'
  write_env
  exit 0
fi

say "Project Zoe -> Termux install"
say "repo: $REPO_ROOT"

pkg_has() { command -v pkg >/dev/null 2>&1 && pkg show "$1" >/dev/null 2>&1; }

install_pkg() {
  local package="$1" binary="${2:-$1}"
  command -v "$binary" >/dev/null 2>&1 && return 0
  if ! pkg_has "$package"; then
    say "enabling tur-repo for $package"
    pkg install -y tur-repo >/dev/null 2>&1 || true
    pkg update -y >/dev/null 2>&1 || true
  fi
  if pkg_has "$package"; then
    say "installing Termux package: $package"
    pkg install -y "$package" || warn "$package failed to install"
  else
    warn "$package is not available; run 'pkg install tur-repo' and retry"
  fi
}

# ---------------------------------------------------------------- 1. packages
if command -v pkg >/dev/null 2>&1; then
  say "updating Termux package lists"
  pkg update -y >/dev/null 2>&1 || warn "pkg update failed; continuing with the current lists"

  # Runtime tools the scripts need: curl for health probes, procps for pkill.
  # Only install the compiler toolchain for the in-process backend.
  PKGS="python git curl procps coreutils"
  if pkg show python-numpy >/dev/null 2>&1; then
    # A prebuilt BLAS-backed numpy is far cheaper than compiling it.
    PKGS="$PKGS python-numpy"
  fi
  if [ "$BACKEND" = "llamacpp" ]; then
    PKGS="$PKGS clang make cmake binutils"
  fi
  say "installing: $PKGS"
  # shellcheck disable=SC2086
  pkg install -y $PKGS

  if ! python3 -c 'import numpy' >/dev/null 2>&1; then
    die "numpy is missing. Run 'pkg install python-numpy' and re-run this installer."
  fi
else
  warn "no 'pkg' command found; skipping Termux packages"
  command -v python3 >/dev/null 2>&1 || die "python3 is required"
fi

# ------------------------------------------------------------------- 2. venv
if [ "$USE_VENV" -eq 1 ]; then
  if [ ! -x "$VENV/bin/python" ]; then
    say "creating virtualenv at $VENV (system site packages visible)"
    mkdir -p "$ZOE_HOME"
    python3 -m venv --system-site-packages "$VENV"
  fi
  PY="$VENV/bin/python"
else
  PY="$(command -v python3)"
fi

say "installing Zoe into $PY"
"$PY" -m pip install --upgrade pip setuptools wheel >/dev/null
"$PY" -m pip install --no-build-isolation -e "$REPO_ROOT"

# --------------------------------------------------------------- 3. engines
if [ "$WANT_OLLAMA" -eq 1 ] && command -v pkg >/dev/null 2>&1; then
  install_pkg ollama ollama
fi

case "$BACKEND" in
  llama-server) install_pkg llama-cpp llama-server ;;
  llama-cli)    install_pkg llama-cpp llama-cli ;;
  llamacpp)
    warn "llamacpp needs a compiled llama-cpp-python; prefer ollama or llama-cli on Termux"
    ;;
esac

# ------------------------------------------------------------- 4. env file
mkdir -p "$ZOE_HOME"
write_env > "$ENV_FILE"
say "wrote $ENV_FILE"

# shellcheck disable=SC2016
if ! grep -q 'zoe/env' "$HOME/.bashrc" 2>/dev/null; then
  {
    echo ''
    echo '# Project Zoe'
    echo '[ -f "$HOME/.zoe/env" ] && . "$HOME/.zoe/env"'
  } >> "$HOME/.bashrc"
  say "added the env file to ~/.bashrc (open a new shell to pick it up)"
fi

# shellcheck disable=SC1090
. "$ENV_FILE"

# --------------------------------------------------------------- 5. model
if [ "$BACKEND" = "ollama" ] && [ "$WANT_OLLAMA" -eq 1 ] && [ "$PULL_MODEL" -eq 1 ]; then
  if command -v ollama >/dev/null 2>&1; then
    if ! curl -fsS --max-time 2 http://127.0.0.1:11434/api/tags >/dev/null 2>&1; then
      say "starting Ollama in the background"
      command -v termux-wake-lock >/dev/null 2>&1 && termux-wake-lock || true
      nohup ollama serve > "$ZOE_HOME/ollama.log" 2>&1 &
      echo $! > "$ZOE_HOME/engine.pid"
      for _ in $(seq 1 30); do
        curl -fsS --max-time 1 http://127.0.0.1:11434/api/tags >/dev/null 2>&1 && break
        sleep 1
      done
    fi
    if curl -fsS --max-time 2 http://127.0.0.1:11434/api/tags >/dev/null 2>&1; then
      if ollama list 2>/dev/null | awk 'NR > 1 {print $1}' | grep -qx "$MODEL"; then
        say "model $MODEL already installed"
      else
        say "pulling $MODEL (this is the slow part; ~400 MB for 0.5B)"
        ollama pull "$MODEL" || warn "pull failed - run: ollama pull $MODEL"
      fi
    else
      warn "Ollama did not start; see $ZOE_HOME/ollama.log"
    fi
  fi
fi

# --------------------------------------------------------------- 6. verify
say "environment check"
set +e
"$PY" -m zoe doctor || true
set -e

cat <<EOF

Done. Zoe is installed with backend: $BACKEND

  source ~/.zoe/env          # or open a new shell
  zoe doctor                 # re-check at any time
  zoe run "build and implement a plan"
  zoe report                 # evolution + 7-tier evaluation

Keep the model warm and the CPU awake:
  bash scripts/termux-start.sh

MCP clients (Claude Desktop, opencode, ...) can launch:
  $PY -m zoe.mcp_server
with ZOE_LLM_BACKEND=$BACKEND in the environment.
EOF
