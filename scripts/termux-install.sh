#!/usr/bin/env bash
# Project Zoe - Termux (Android) installer.
#
#   bash scripts/termux-install.sh                    # Ollama + qwen2.5:0.5b
#   bash scripts/termux-install.sh --model llama3.2:1b
#   bash scripts/termux-install.sh --backend llama-cli --model-file ~/models/tiny.gguf
#   bash scripts/termux-install.sh --no-ollama        # keep the mock engine only
#
# Everything is idempotent: re-running upgrades the venv and re-checks the
# environment. Nothing is installed outside $HOME except Termux packages.
set -euo pipefail

BACKEND="ollama"
MODEL="${ZOE_OLLAMA_MODEL:-qwen2.5:0.5b}"
MODEL_FILE="${ZOE_GGUF_PATH:-}"
WANT_OLLAMA=1
PULL_MODEL=1
USE_VENV=1
ASSUME_YES=0

ZOE_HOME="${ZOE_HOME:-$HOME/.zoe}"
VENV="$ZOE_HOME/venv"
ENV_FILE="$ZOE_HOME/env"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

say()  { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[!]\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31m[x]\033[0m %s\n' "$*" >&2; exit 1; }

usage() {
  sed -n '2,12p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
  exit 0
}

while [ $# -gt 0 ]; do
  case "$1" in
    --backend)      BACKEND="${2:?}"; shift 2 ;;
    --model)        MODEL="${2:?}"; shift 2 ;;
    --model-file)   MODEL_FILE="${2:?}"; shift 2 ;;
    --no-ollama)    WANT_OLLAMA=0; PULL_MODEL=0; shift ;;
    --no-pull)      PULL_MODEL=0; shift ;;
    --no-venv)      USE_VENV=0; shift ;;
    --yes|-y)       ASSUME_YES=1; shift ;;
    -h|--help)      usage ;;
    *) die "unknown option: $1 (try --help)" ;;
  esac
done

is_termux() {
  [ -n "${TERMUX_VERSION:-}" ] || case "${PREFIX:-}" in *com.termux*) return 0 ;; esac
  return 1
}

if ! is_termux; then
  warn "This script targets Termux on Android; ${PREFIX:-this system} does not look like it."
  warn "On desktop Linux/macOS use: pip install -e '.[llm]' and ZOE_LLM_BACKEND=ollama"
  [ "$ASSUME_YES" -eq 1 ] || die "refusing to run without --yes"
fi

say "Project Zoe -> Termux install"
say "repo: $REPO_ROOT"

# ---------------------------------------------------------------- 1. packages
if command -v pkg >/dev/null 2>&1; then
  say "updating Termux package lists"
  pkg update -y >/dev/null 2>&1 || warn "pkg update failed; continuing with the current lists"

  PKGS="python git clang make cmake binutils"
  # python-numpy ships a prebuilt BLAS-backed numpy: far cheaper than compiling.
  if pkg show python-numpy >/dev/null 2>&1; then
    PKGS="$PKGS python-numpy"
  fi
  say "installing: $PKGS"
  # shellcheck disable=SC2086
  pkg install -y $PKGS

  if ! python3 -c 'import numpy' >/dev/null 2>&1; then
    say "numpy not available as a package; installing from pip (this can take a while)"
    python3 -m pip install --upgrade pip >/dev/null
    python3 -m pip install 'numpy>=1.24'
  fi
else
  warn "no 'pkg' command found; skipping Termux packages"
fi

# ------------------------------------------------------------------- 2. venv
if [ "$USE_VENV" -eq 1 ]; then
  if [ ! -x "$VENV/bin/python" ]; then
    say "creating virtualenv at $VENV (system site packages visible)"
    mkdir -p "$ZOE_HOME"
    python3 -m venv --system-site-packages "$VENV"
  fi
  PY="$VENV/bin/python"
else
  PY="$(command -v python3)"
fi

say "installing Zoe into $PY"
"$PY" -m pip install --upgrade pip setuptools wheel >/dev/null
"$PY" -m pip install --no-build-isolation -e "$REPO_ROOT"

# --------------------------------------------------------------- 3. engines
if [ "$WANT_OLLAMA" -eq 1 ] && command -v pkg >/dev/null 2>&1; then
  if ! command -v ollama >/dev/null 2>&1; then
    say "installing Ollama (Termux package)"
    pkg install -y ollama || warn "ollama package unavailable; falling back to mock"
  fi
fi

if [ "$BACKEND" = "llama-cli" ] && command -v pkg >/dev/null 2>&1; then
  if ! command -v llama-cli >/dev/null 2>&1; then
    say "installing llama.cpp CLI (Termux package)"
    pkg install -y llama-cpp || warn "llama-cpp package unavailable"
  fi
fi

# ------------------------------------------------------------- 4. env file
mkdir -p "$ZOE_HOME"
{
  echo "# Project Zoe environment - generated by scripts/termux-install.sh"
  echo "export ZOE_LLM_BACKEND=\"$BACKEND\""
  echo "export ZOE_OLLAMA_MODEL=\"$MODEL\""
  if [ -n "$MODEL_FILE" ]; then
    echo "export ZOE_GGUF_PATH=\"$MODEL_FILE\""
  fi
  echo "export ZOE_LEDGER_PATH=\"$ZOE_HOME/ledger.jsonl\""
  echo "export PATH=\"$ZOE_HOME/venv/bin:\$PATH\""
} > "$ENV_FILE"
say "wrote $ENV_FILE"

# shellcheck disable=SC2016
if ! grep -q 'zoe/env' "$HOME/.bashrc" 2>/dev/null; then
  {
    echo ''
    echo '# Project Zoe'
    echo '[ -f "$HOME/.zoe/env" ] && . "$HOME/.zoe/env"'
  } >> "$HOME/.bashrc"
  say "added the env file to ~/.bashrc (open a new shell to pick it up)"
fi

# shellcheck disable=SC1090
. "$ENV_FILE"

# --------------------------------------------------------------- 5. model
if [ "$BACKEND" = "ollama" ] && [ "$PULL_MODEL" -eq 1 ]; then
  if command -v ollama >/dev/null 2>&1; then
    if ! curl -fsS --max-time 2 http://127.0.0.1:11434/api/tags >/dev/null 2>&1; then
      say "starting Ollama in the background"
      command -v termux-wake-lock >/dev/null 2>&1 && termux-wake-lock || true
      nohup ollama serve > "$ZOE_HOME/ollama.log" 2>&1 &
      for _ in $(seq 1 30); do
        curl -fsS --max-time 1 http://127.0.0.1:11434/api/tags >/dev/null 2>&1 && break
        sleep 1
      done
    fi
    if curl -fsS --max-time 2 http://127.0.0.1:11434/api/tags >/dev/null 2>&1; then
      if ollama list 2>/dev/null | awk '{print $1}' | grep -qx "$MODEL"; then
        say "model $MODEL already installed"
      else
        say "pulling $MODEL (this is the slow part; ~400 MB for 0.5B)"
        ollama pull "$MODEL" || warn "pull failed - run: ollama pull $MODEL"
      fi
    else
      warn "Ollama did not start; see $ZOE_HOME/ollama.log"
    fi
  fi
fi

# --------------------------------------------------------------- 6. verify
say "environment check"
set +e
"$PY" -m zoe doctor || true
set -e

cat <<EOF

Done. Zoe is installed.

  source ~/.zoe/env          # or open a new shell
  zoe doctor                 # re-check at any time
  zoe run "build and implement a plan"
  zoe report                 # evolution + 7-tier evaluation

Keep the model warm and the CPU awake:
  bash scripts/termux-start.sh

MCP clients (Claude Desktop, opencode, ...) can launch:
  $PY -m zoe.mcp_server
with ZOE_LLM_BACKEND=$BACKEND in the environment.
EOF
